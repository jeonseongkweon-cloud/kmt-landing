do $$
begin
  if not exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='guardians' and column_name='sms_enabled'
  ) then
    alter table public.guardians add column sms_enabled boolean not null default false;
    update public.guardians set sms_enabled=true
    where is_primary=true
      and nullif(regexp_replace(coalesce(phone,''), '[^0-9]', '', 'g'), '') is not null;
  end if;
end $$;

create table if not exists public.sms_settings (
  id smallint primary key default 1 check (id = 1),
  attendance_enabled boolean not null default true,
  attendance_template text not null default '{학생명} 학생이 {시간} 계명태권도에 도착했습니다.',
  sender_label text not null default '계명태권도',
  updated_by uuid references auth.users(id) on delete set null default auth.uid(),
  updated_at timestamptz not null default timezone('utc', now())
);

insert into public.sms_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.sms_outbox (
  id uuid primary key default gen_random_uuid(),
  attendance_id uuid not null references public.attendance(id) on delete cascade,
  student_id uuid not null references public.students(id) on delete restrict,
  guardian_id uuid not null references public.guardians(id) on delete restrict,
  recipient_name text,
  recipient_phone text not null,
  message text not null,
  status text not null default 'pending' check (status in ('pending','sending','sent','failed','cancelled')),
  attempts smallint not null default 0 check (attempts >= 0),
  next_attempt_at timestamptz not null default now(),
  locked_at timestamptz,
  locked_by text,
  sent_at timestamptz,
  last_error text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (attendance_id, guardian_id)
);

create table if not exists public.sms_logs (
  id bigint generated by default as identity primary key,
  outbox_id uuid not null references public.sms_outbox(id) on delete cascade,
  from_status text,
  to_status text not null,
  result_message text,
  device_id text,
  created_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.sms_sender_status (
  id smallint primary key default 1 check (id = 1),
  device_id text,
  device_name text,
  is_enabled boolean not null default false,
  last_seen_at timestamptz,
  last_sent_at timestamptz,
  app_version text,
  updated_at timestamptz not null default timezone('utc', now())
);

insert into public.sms_sender_status (id) values (1) on conflict (id) do nothing;

create index if not exists sms_outbox_status_idx on public.sms_outbox (status, next_attempt_at, created_at);
create index if not exists sms_outbox_student_idx on public.sms_outbox (student_id, created_at desc);
create index if not exists sms_logs_outbox_idx on public.sms_logs (outbox_id, created_at desc);

