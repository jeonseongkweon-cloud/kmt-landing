create or replace function public.kmt_log_sms_status()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if tg_op='INSERT' or old.status is distinct from new.status then
    insert into public.sms_logs(outbox_id,from_status,to_status,result_message,device_id)
    values(new.id,case when tg_op='UPDATE' then old.status else null end,new.status,new.last_error,new.locked_by);
  end if;
  return new;
end;
$$;

drop trigger if exists sms_outbox_log_status on public.sms_outbox;
create trigger sms_outbox_log_status after insert or update of status on public.sms_outbox
for each row execute function public.kmt_log_sms_status();

create or replace function public.kmt_render_attendance_sms(p_student_name text, p_checked_at timestamptz)
returns text language plpgsql stable security invoker set search_path = public as $$
declare v_template text;
begin
  select attendance_template into v_template from public.sms_settings where id = 1;
  return replace(replace(coalesce(v_template, '{학생명} 학생이 {시간} 계명태권도에 도착했습니다.'),
    '{학생명}', coalesce(p_student_name, '원생')),
    '{시간}', to_char(timezone('Asia/Seoul', p_checked_at), 'HH24시 MI분'));
end;
$$;

create or replace function public.kmt_queue_attendance_sms()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_student_name text; v_guardian record; v_message text; v_enabled boolean;
begin
  if new.student_id is null then return new; end if;

  if new.status not in ('present','late') then
    update public.sms_outbox set status='cancelled', last_error='출석 상태 변경으로 취소'
    where attendance_id=new.id and status in ('pending','failed');
    return new;
  end if;

  select attendance_enabled into v_enabled from public.sms_settings where id=1;
  if coalesce(v_enabled, false) = false then return new; end if;
  select name into v_student_name from public.students where id=new.student_id;
  v_message := public.kmt_render_attendance_sms(v_student_name, new.checked_at);

  for v_guardian in
    select id, name, regexp_replace(coalesce(phone,''), '[^0-9]', '', 'g') as phone
    from public.guardians
    where student_id=new.student_id and sms_enabled=true
  loop
    if length(v_guardian.phone) between 10 and 11 then
      insert into public.sms_outbox(attendance_id,student_id,guardian_id,recipient_name,recipient_phone,message)
      values(new.id,new.student_id,v_guardian.id,v_guardian.name,v_guardian.phone,v_message)
      on conflict(attendance_id,guardian_id) do update set
        recipient_name=excluded.recipient_name,
        recipient_phone=excluded.recipient_phone,
        message=excluded.message,
        status=case when public.sms_outbox.status in ('failed','cancelled') then 'pending' else public.sms_outbox.status end,
        next_attempt_at=case when public.sms_outbox.status in ('failed','cancelled') then now() else public.sms_outbox.next_attempt_at end,
        last_error=case when public.sms_outbox.status in ('failed','cancelled') then null else public.sms_outbox.last_error end;
    end if;
  end loop;
  return new;
exception when others then
  -- 문자 대기 생성 오류가 출석 저장을 막지 않도록 완전히 분리한다.
  raise warning 'KMT SMS queue error for attendance %: %', new.id, sqlerrm;
  return new;
end;
$$;

drop trigger if exists attendance_queue_sms on public.attendance;
create trigger attendance_queue_sms after insert or update of status, checked_at on public.attendance
for each row execute function public.kmt_queue_attendance_sms();

create or replace function public.kmt_retry_sms(p_outbox_id uuid)
returns public.sms_outbox language plpgsql security invoker set search_path=public as $$
declare v_row public.sms_outbox;
begin
  if not public.kmt_is_admin() then raise exception '관리자 권한이 필요합니다.'; end if;
  update public.sms_outbox set status='pending',next_attempt_at=now(),locked_at=null,locked_by=null,last_error=null
  where id=p_outbox_id and status in ('failed','cancelled') returning * into v_row;
  return v_row;
end;
$$;

revoke all on function public.kmt_retry_sms(uuid) from public;
grant execute on function public.kmt_retry_sms(uuid) to authenticated;

